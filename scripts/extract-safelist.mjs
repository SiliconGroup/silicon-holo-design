import { createGenerator } from '@unocss/core'
import presetUno from '@unocss/preset-uno'
import { readFileSync, writeFileSync } from 'fs'
import { globSync } from 'glob'
import { join, resolve } from 'path'

const root = resolve(import.meta.dirname, '..')
const distDir = join(root, 'dist')

const { presetSiliconHolo } = await import(join(distDir, 'preset', 'index.js'))
const publishedPreset = presetSiliconHolo()
const extractionPreset = { ...publishedPreset, safelist: [] }
const sourceFiles = globSync('src/**/*.{ts,tsx}', {
  cwd: root,
  absolute: true,
  ignore: ['**/*.test.{ts,tsx}', '**/preset/safelist.ts'],
})
const code = sourceFiles.map(file => readFileSync(file, 'utf-8')).join('\n')

const uno = await createGenerator({ presets: [presetUno({ preflight: 'on-demand', variablePrefix: 'shd-un-' }), extractionPreset] })
const tokens = new Set()
await uno.applyExtractors(code, 'dist.js', tokens)
const result = await uno.generate(tokens)
const matched = [...result.matched].sort()

const output = `// Auto-generated by scripts/extract-safelist.mjs — do not edit manually
export const safelist: string[] = ${JSON.stringify(matched, null, 2)}
`

writeFileSync(join(root, 'src', 'preset', 'safelist.ts'), output)
writeFileSync(join(root, 'src', 'styles', 'generated-utilities.css'), `/* Auto-generated by scripts/extract-safelist.mjs — do not edit manually */\n@layer shd-prebuilt {\n${result.css}\n}\n`)
console.log(`✓ Extracted ${matched.length} UnoCSS classes → safelist + generated utility CSS`)
